#include <bits/stdc++.h>
using namespace std;

// A "許蓋功字元" is a character whose Big5 encoding's second byte == '\' (0x5C).
// Judge input is UTF-8. These are the Unicode codepoints of all such Big5 chars.
static const int CPS[] = {
    0x3B1,0x30C4,0x4E48,0x4F62,0x4FDE,0x5045,0x509C,0x515D,0x529F,0x5412,
    0x542D,0x577C,0x57A5,0x587F,0x58A6,0x5A09,0x5A16,0x5AF9,0x5B1E,0x5B40,
    0x5C10,0x5CA4,0x5D24,0x5E4B,0x5EC4,0x60DD,0x6127,0x63CA,0x64FA,0x669D,
    0x67AF,0x67E6,0x69D9,0x6B7F,0x6C7B,0x6C94,0x6D82,0x6DDA,0x6EDC,0x6F7F,
    0x7019,0x7035,0x712E,0x71E1,0x727E,0x72D6,0x7366,0x73EE,0x7435,0x749E,
    0x7912,0x7A1E,0x7A40,0x7BA4,0x7D85,0x7E37,0x7F61,0x80D0,0x82D2,0x833B,
    0x838D,0x84CB,0x850C,0x878F,0x87B0,0x8A31,0x8C79,0x8D15,0x8D68,0x8DDA,
    0x8E0A,0x8EA1,0x9103,0x9140,0x9145,0x9186,0x923E,0x93AA,0x95B1,0x9910,
    0x9924,0x99F9,0x9A31,0x9ACF,0x9C4B,0x9C6D,0x9EE0,0xFE4F
};

int main(){
    unordered_set<int> S(begin(CPS), end(CPS));
    string line;
    // read raw bytes line by line; getline splits on '\n'
    while(getline(cin, line)){
        // strip trailing '\r'
        while(!line.empty() && (line.back()=='\r' || line.back()=='\n'))
            line.pop_back();
        bool found=false;
        size_t i=0, n=line.size();
        while(i<n){
            unsigned char c=line[i];
            int cp; int len;
            if(c<0x80){ cp=c; len=1; }
            else if((c>>5)==0x6){ cp=c&0x1F; len=2; }
            else if((c>>4)==0xE){ cp=c&0x0F; len=3; }
            else if((c>>3)==0x1E){ cp=c&0x07; len=4; }
            else { i++; continue; }
            if(i+len>n){ break; }
            for(int k=1;k<len;k++){
                cp=(cp<<6)|(line[i+k]&0x3F);
            }
            i+=len;
            if(S.count(cp)){ found=true; }
        }
        cout << (found ? "Yes" : "No") << "\n";
    }
    return 0;
}
