// e390 許功蓋問題 — 自寫解
// ZeroJudge 環境輸入為 UTF-8。某字若其 Big5 編碼為「兩位元組且尾位元組 0x5C」
// 便會造成許功蓋問題,輸出 Yes,否則 No。
// 反斜線 '\' 的 Big5 為單位元組 0x5C,不屬此類,輸出 No。
// 下表為本機以 iconv 列舉所有 Big5=?? 5C(兩位元組)之字元、轉回 Unicode 得到的碼位,
// 共 88 個(自行產生,非抄襲外部解答)。
#include <bits/stdc++.h>
using namespace std;

// 解出 UTF-8 字串第一個 Unicode 碼位
static uint32_t decode_utf8(const string &s) {
    const unsigned char *p = reinterpret_cast<const unsigned char *>(s.c_str());
    if (p[0] < 0x80) return p[0];
    else if ((p[0] >> 5) == 0x6)
        return ((p[0] & 0x1F) << 6) | (p[1] & 0x3F);
    else if ((p[0] >> 4) == 0xE)
        return ((p[0] & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F);
    else
        return ((p[0] & 0x07) << 18) | ((p[1] & 0x3F) << 12) |
               ((p[2] & 0x3F) << 6) | (p[3] & 0x3F);
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    static const unordered_set<uint32_t> xgg = {
        0x03B1,0x30C4,0x4E48,0x4F62,0x4FDE,0x5045,0x509C,0x515D,0x529F,0x5412,
        0x542D,0x577C,0x57A5,0x587F,0x58A6,0x5A09,0x5A16,0x5AF9,0x5B1E,0x5B40,
        0x5C10,0x5CA4,0x5D24,0x5E4B,0x5EC4,0x60DD,0x6127,0x63CA,0x64FA,0x669D,
        0x67AF,0x67E6,0x69D9,0x6B7F,0x6C7B,0x6C94,0x6D82,0x6DDA,0x6EDC,0x6F7F,
        0x7019,0x7035,0x712E,0x71E1,0x727E,0x72D6,0x7366,0x73EE,0x7435,0x749E,
        0x7912,0x7A1E,0x7A40,0x7BA4,0x7D85,0x7E37,0x7F61,0x80D0,0x82D2,0x833B,
        0x838D,0x84CB,0x850C,0x878F,0x87B0,0x8A31,0x8C79,0x8D15,0x8D68,0x8DDA,
        0x8E0A,0x8EA1,0x9103,0x9140,0x9145,0x9186,0x923E,0x93AA,0x95B1,0x9910,
        0x9924,0x99F9,0x9A31,0x9ACF,0x9C4B,0x9C6D,0x9EE0,0xFE4F
    };

    string token;
    while (cin >> token) {
        uint32_t cp = decode_utf8(token);
        cout << (xgg.count(cp) ? "Yes" : "No") << '\n';
    }
    return 0;
}
