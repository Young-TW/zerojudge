#include <iostream>

using namespace std;

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int edges[24] = {
        (1 << 0) | (1 << 2), (1 << 0) | (1 << 3),
        (1 << 1) | (1 << 2), (1 << 1) | (1 << 5),
        (1 << 2) | (1 << 3), (1 << 2) | (1 << 5), (1 << 2) | (1 << 6),
        (1 << 3) | (1 << 4), (1 << 3) | (1 << 6), (1 << 3) | (1 << 7),
        (1 << 4) | (1 << 7),
        (1 << 5) | (1 << 6), (1 << 5) | (1 << 8), (1 << 5) | (1 << 9),
        (1 << 6) | (1 << 7), (1 << 6) | (1 << 9), (1 << 6) | (1 << 10),
        (1 << 7) | (1 << 10), (1 << 7) | (1 << 11),
        (1 << 8) | (1 << 9),
        (1 << 9) | (1 << 10), (1 << 9) | (1 << 12),
        (1 << 10) | (1 << 11), (1 << 10) | (1 << 12)
    };

    int dp[1 << 13];
    dp[0] = 1;
    for (int S = 1; S < (1 << 13); ++S) {
        dp[S] = 0;
        for (int i = 0; i < 13; ++i) {
            if ((S >> i) & 1) {
                if (dp[S ^ (1 << i)] == 0) {
                    dp[S] = 1;
                    break;
                }
            }
        }
        if (dp[S] == 1) continue;
        for (int i = 0; i < 24; ++i) {
            if ((S & edges[i]) == edges[i]) {
                if (dp[S ^ edges[i]] == 0) {
                    dp[S] = 1;
                    break;
                }
            }
        }
    }

    int n;
    while (cin >> n) {
        for (int i = 0; i < n; ++i) {
            int x;
            cin >> x;
            cout << dp[x] << (i == n - 1 ? "" : " ");
        }
        cout << "\n";
    }

    return 0;
}
